use std::any::Any;
use std::rc::Rc;

use crate::core::commontypes::enabled_t;
use crate::core::global::KataError;
use crate::neuralnet::desc::ModelDesc;
use crate::neuralnet::nneval::NNResultBuf;
use crate::neuralnet::nninputs::NNOutput;
use crate::port::executor::LocalBoxFuture;

/// upstream: ComputeContext (nninterface.h)
// A handle to cross-thread cross-gpu initialization state.
// Create one of these per process, although creating more is fine.
pub trait ComputeContext {
  fn as_any(&self) -> &dyn Any;
}

/// upstream: ComputeHandle (nninterface.h)
// A handle to the local compute backend. Not thread-safe, each handle should
// only be used by one thread.
pub trait ComputeHandle {
  fn as_any_mut(&mut self) -> &mut dyn Any;
  fn as_any(&self) -> &dyn Any;
}

/// upstream: InputBuffers (nninterface.h)
// The interface for the input buffers for the neural network. The MCTS code
// uses this interface to pass data into the neural network for computation.
pub trait InputBuffers {
  fn as_any_mut(&mut self) -> &mut dyn Any;
}

/// upstream: LoadedModel (nninterface.h)
// A handle to the loaded neural network model.
pub trait LoadedModel {
  fn as_any(&self) -> &dyn Any;
}

/// upstream: NeuralNet (nninterface.h)
// Generic interface to neural net inference.
// There is a single CUDA backend.
pub trait NeuralNet {
  /// upstream: NeuralNet::globalInitialize (nninterface.h)
  // Call globalInitialize() once upon program startup to construct the net.
  fn global_initialize(&self);
  /// upstream: NeuralNet::globalCleanup (nninterface.h)
  // Call globalCleanup() at program termination.
  fn global_cleanup(&self);

  /// upstream: NeuralNet::printDevices (nninterface.h)
  //Print available backend devices
  fn print_devices(&self);

  // Model I/O -----------------------------------------------------------------

  /// upstream: NeuralNet::loadModelFile (nninterface.h)
  /// PORT NOTE: core has no file IO (CLAUDE.md, D6): the host passes the model's bytes; `file` is
  /// only a name for messages. freeLoadedModel is Drop.
  fn load_model_file(&self, file: &str, model_bytes: Vec<u8>, expected_sha256: &str) -> Result<Box<dyn LoadedModel>, KataError>;

  /// upstream: NeuralNet::getModelDesc (nninterface.h)
  fn get_model_desc<'a>(&self, loaded_model: &'a dyn LoadedModel) -> &'a ModelDesc;

  // Context -------------------------------------------------------------------

  /// upstream: NeuralNet::createComputeContext (nninterface.h)
  /// PORT NOTE: `Logger* logger` dropped (log crate). freeComputeContext is Drop.
  //A ComputeContext should NOT be freed until all ComputeHandles created using it have also been freed.
  fn create_compute_context(
    &self,
    //The indices of all gpus that this context will be used for.
    //-1 as an entry indicates to select a default
    gpu_idxs: &[i32],
    nn_x_len: i32,
    nn_y_len: i32,
    open_cl_tuner_file: &str,
    home_data_dir_override: &str,
    open_cl_re_tune_per_board_size: bool,
    use_fp16_mode: enabled_t,
    use_nhwc_mode: enabled_t,
    loaded_model: &dyn LoadedModel,
  ) -> Result<Box<dyn ComputeContext>, KataError>;

  // Compute Handle -----------------------------------------------------------------

  /// upstream: NeuralNet::createComputeHandle (nninterface.h)
  /// PORT NOTE: `Logger* logger` dropped. The handle is moved into the serve task, so a backend
  /// keeps (clones) whatever it needs from `context` instead of a raw pointer.
  /// freeComputeHandle is Drop.
  // Any given thread should only ever create one of these at a time.
  // When using the CUDA backend, will mutably set the GPU that this thread is
  // associated with to the specified index. If logger is specified, may output
  // some info messages to it. If requireExactNNLen is true, the backend is
  // allowed to assume that all boards to evaluate will be of size exactly equal
  // to (nnXLen,nnYLen) rather than smaller, and skip any masking operations.
  // gpuIdxForThisThread == -1 indicates to select a default GPU.
  fn create_compute_handle(
    &self,
    context: &dyn ComputeContext,
    loaded_model: &dyn LoadedModel,
    max_batch_size: i32,
    require_exact_nn_len: bool,
    inputs_use_nhwc: bool,
    gpu_idx_for_this_thread: i32,
    server_thread_idx: i32,
  ) -> Result<Box<dyn ComputeHandle>, KataError>;

  /// upstream: NeuralNet::isUsingFP16 (nninterface.h)
  fn is_using_fp16(&self, compute_handle: &dyn ComputeHandle) -> bool;

  //Input Buffers ---------------------------------------------------------------

  /// upstream: NeuralNet::createInputBuffers (nninterface.h)
  /// freeInputBuffers is Drop.
  fn create_input_buffers(&self, loaded_model: &dyn LoadedModel, max_batch_size: i32, nn_x_len: i32, nn_y_len: i32) -> Box<dyn InputBuffers>;

  //The neural net takes in 2 tensors as input.
  //One of them ("spatial") is 3-dimensional per-batch-element (4-dimensional including the batch dimension N),
  //containing floats for the values of different features (C) across the space of the board (H,W),
  //such as placement of stones and prior move locations.
  //The other ("global") is 1-dimensional per-batch-element containing floats for features that are
  //global to the board state, such as game rules and komi.

  //Perform Neural Net Evals ---------------------------------------------------------

  // Preconditions:
  // buffers inputBufs[nIdx]->{rowSpatial,rowGlobal} have been filled with input data for all values of nIdx in [0,numBatchEltsFilled-1]
  // outputs has length numBatchEltsFilled containing allocated but possibly-uninitialized NNOutput structs.

  // Result: mutably writes the results of the numBatchEltsFilled many parallel neural net evaluations
  // into the NNOutput structs.
  // All outputs are in logits - all final activation functions softmax, tanh, etc. are NOT applied.
  /// upstream: NeuralNet::getOutput (nninterface.h)
  /// PORT NOTE: async (PORTING.md §11: GPU readback is async; a CPU backend must yield to the
  /// event loop). Returns Result because a backend may fail (device loss), as upstream's GPU
  /// backends throw. `outputs` are the caller-built NNOutputs (nnXLen, nnYLen, whiteOwnerMap
  /// allocated or None), one per row, as upstream.
  fn get_output<'a>(
    &'a self,
    compute_handle: &'a mut dyn ComputeHandle,
    buffers: &'a mut dyn InputBuffers,
    num_batch_elts_filled: i32,
    input_bufs: &'a [Rc<NNResultBuf>],
    outputs: &'a mut [NNOutput],
  ) -> LocalBoxFuture<'a, Result<(), KataError>>;
}
