const POW_OFF: u64 = 0x3fe6955500000000;

/// Compute y+TAIL = log(x) where the rounded result is y and TAIL has about
/// additional 15 bits precision.  IX is the bit representation of x, but
/// normalized in the subnormal range using the sign bit for the exponent.
fn pow_log_inline(ix: u64, tail: &mut f64) -> f64 {
  /* x = 2^k z; where z is in range [OFF,2*OFF) and exact.
     The range is split into N subintervals.
     The ith subinterval contains z and c is near its center.  */
  let tmp: u64 = ix.wrapping_sub(POW_OFF);
  let i: usize = ((tmp >> (52 - POW_LOG_TABLE_BITS)) % N_POW_LOG) as usize;
  let k: i32 = ((tmp as i64) >> 52) as i32; /* arithmetic shift */
  let iz: u64 = ix.wrapping_sub(tmp & (0xfffu64 << 52));
  let z: f64 = asdouble(iz);
  let kd: f64 = k as f64;

  /* log(x) = k*Ln2 + log(c) + log1p(z/c-1).  */
  let invc: f64 = c(POW_LOG_TAB[3 * i]);
  let logc: f64 = c(POW_LOG_TAB[3 * i + 1]);
  let logctail: f64 = c(POW_LOG_TAB[3 * i + 2]);

  /* Note: 1/c is j/N or j/N/2 where j is an integer in [N,2N) and
     |z/c - 1| < 1/N, so r = z/c - 1 is exactly representible.  */
  let r: f64 = z.mul_add(invc, -1.0);

  /* k*Ln2 + log(c) + r.  */
  let t1: f64 = kd.mul_add(c(POW_LOG_LN2HI), logc);
  let t2: f64 = r + t1;
  let lo1: f64 = kd.mul_add(c(POW_LOG_LN2LO), logctail);
  let lo2: f64 = r + (t1 - t2);

  /* Evaluation is optimized assuming superscalar pipelined execution.  */
  let a = |i: usize| c(POW_LOG_POLY[i]);
  let ar: f64 = r * a(0); /* A[0] = -0.5.  */
  let ar2: f64 = r * ar;
  let ar3: f64 = r * ar2;
  /* k*Ln2 + log(c) + r + A[0]*r*r.  */
  let hi: f64 = t2 + ar2;
  let lo3: f64 = r.mul_add(ar, -ar2);
  let lo4: f64 = ar2 + (t2 - hi);
  /* p = log1p(r) - r - A[0]*r*r.  */
  // p = (ar3 * (A[1] + r * A[2] + ar2 * (A[3] + r * A[4] + ar2 * (A[5] + r * A[6]))));
  let q: f64 = ar2.mul_add(ar2.mul_add(r.mul_add(a(6), a(5)), r.mul_add(a(4), a(3))), r.mul_add(a(2), a(1)));
  // lo = lo1 + lo2 + lo3 + lo4 + p;  (the final + p contracted with p = ar3 * q)
  let lo: f64 = ar3.mul_add(q, lo4 + (lo3 + (lo1 + lo2)));
  let y: f64 = hi + lo;
  *tail = lo + (hi - y);
  y
}

/// See exp_specialcase; pow's version keeps the sign of the result in sbits.
fn pow_specialcase(tmp: f64, mut sbits: u64, ki: u64) -> f64 {
  let scale: f64;
  let mut y: f64;

  if (ki & 0x80000000) == 0 {
    /* k > 0, the exponent of scale might have overflowed by <= 460.  */
    sbits = sbits.wrapping_sub(1009u64 << 52);
    scale = asdouble(sbits);
    y = tmp.mul_add(scale, scale);
    // PORT NOTE: the `#if !HAVE_FAST_FMA` DBL_MAX special case is not in the FMA build.
    return y * f64::from_bits(0x7f00000000000000); // 0x1p1009
  }
  /* k < 0, need special care in the subnormal range.  */
  sbits = sbits.wrapping_add(1022u64 << 52);
  /* Note: sbits is signed scale.  */
  scale = asdouble(sbits);
  let scale_tmp = tmp * scale;
  y = scale + scale_tmp;
  if y.abs() < 1.0 {
    /* Round y to the right precision before scaling it into the subnormal
       range to avoid double rounding that can cause 0.5+E/2 ulp error where
       E is the worst-case ulp error outside the subnormal range.  So this
       is only useful if the goal is better than 1 ulp worst-case error.  */
    let mut one: f64 = 1.0;
    if y < 0.0 {
      one = -1.0;
    }
    let mut lo: f64 = scale_tmp + (scale - y);
    let hi: f64 = y + one;
    lo += y + (one - hi);
    y = (hi + lo) - one;
    /* Fix the sign of 0.  */
    if y == 0.0 {
      y = asdouble(sbits & 0x8000000000000000);
    }
    /* The underflow exception needs to be signaled explicitly.  */
    // PORT NOTE: force_eval only raises a flag; dropped.
  }
  y *= f64::from_bits(0x0010000000000000); // 0x1p-1022
  y
}

const SIGN_BIAS: u32 = 0x800 << EXP_TABLE_BITS;

/// Computes sign*exp(x+xtail) where |xtail| < 2^-8/N and |xtail| <= |x|.
/// The sign_bias argument is SIGN_BIAS or 0 and sets the sign to -1 or 1.
fn pow_exp_inline(x: f64, xtail: f64, sign_bias: u32) -> f64 {
  let mut abstop: u32;

  abstop = top12(x) & 0x7ff;
  if abstop.wrapping_sub(top12(f64::from_bits(0x3c90000000000000)))
    >= top12(512.0) - top12(f64::from_bits(0x3c90000000000000))
  {
    if abstop.wrapping_sub(top12(f64::from_bits(0x3c90000000000000))) >= 0x80000000 {
      /* Avoid spurious underflow for tiny x.  */
      /* Note: 0 is common input.  */
      let one: f64 = 1.0 + x;
      return if sign_bias != 0 { -one } else { one };
    }
    if abstop >= top12(1024.0) {
      /* Note: inf and nan are already handled.  */
      if asuint64(x) >> 63 != 0 {
        return math_uflow(sign_bias);
      } else {
        return math_oflow(sign_bias);
      }
    }
    /* Large x is special cased below.  */
    abstop = 0;
  }

  /* exp(x) = 2^(k/N) * exp(r), with exp(r) in [2^(-1/2N),2^(1/2N)].  */
  /* x = ln2/N*k + r, with int k and r in [-ln2/2N, ln2/2N].  */
  let mut kd: f64 = x.mul_add(c(EXP_INVLN2N), c(EXP_SHIFT));
  let ki: u64 = asuint64(kd);
  kd -= c(EXP_SHIFT);
  let mut r: f64 = kd.mul_add(c(EXP_NEGLN2LON), kd.mul_add(c(EXP_NEGLN2HIN), x));
  /* The code assumes 2^-200 < |xtail| < 2^-8/N.  */
  r += xtail;
  /* 2^(k/N) ~= scale * (1 + tail).  */
  let idx: u64 = 2 * (ki % N_EXP);
  let top: u64 = ki.wrapping_add(sign_bias as u64) << (52 - EXP_TABLE_BITS);
  let tail: f64 = asdouble(EXP_TAB[idx as usize]);
  /* This is only a valid scale when -1023*N < k < 1024*N.  */
  let sbits: u64 = top.wrapping_add(EXP_TAB[idx as usize + 1]);
  /* exp(x) = 2^(k/N) * exp(r) ~= scale + scale * (tail + exp(r) - 1).  */
  /* Evaluation is optimized assuming superscalar pipelined execution.  */
  let r2: f64 = r * r;
  /* Without fma the worst case error is 0.25/N ulp larger.  */
  /* Worst case error is less than 0.5+1.11/N+(abs poly error * 2^53) ulp.  */
  let t0: f64 = r + tail;
  let t1: f64 = r2.mul_add(r.mul_add(c(EXP_POLY[1]), c(EXP_POLY[0])), t0);
  let tmp: f64 = (r2 * r2).mul_add(r.mul_add(c(EXP_POLY[3]), c(EXP_POLY[2])), t1);
  if abstop == 0 {
    return pow_specialcase(tmp, sbits, ki);
  }
  let scale: f64 = asdouble(sbits);
  /* Note: tmp == 0 or |tmp| > 2^-200 and scale > 2^-739, so there
     is no spurious underflow here even without fma.  */
  tmp.mul_add(scale, scale)
}

/// Returns 0 if not int, 1 if odd int, 2 if even int.  The argument is
/// the bit representation of a non-zero finite floating-point value.
fn checkint(iy: u64) -> i32 {
  let e: i32 = (iy >> 52 & 0x7ff) as i32;
  if e < 0x3ff {
    return 0;
  }
  if e > 0x3ff + 52 {
    return 2;
  }
  if iy & ((1u64 << (0x3ff + 52 - e)) - 1) != 0 {
    return 0;
  }
  if iy & (1u64 << (0x3ff + 52 - e)) != 0 {
    return 1;
  }
  2
}

/// Returns 1 if input is the bit representation of 0, infinity or nan.
fn zeroinfnan(i: u64) -> bool {
  i.wrapping_mul(2).wrapping_sub(1) >= 2u64.wrapping_mul(asuint64(f64::INFINITY)).wrapping_sub(1)
}

/// C `pow(double, double)` (glibc 2.44 `__pow_fma`). Use instead of `f64::powf`.
pub fn powf(x: f64, y: f64) -> f64 {
  let mut sign_bias: u32 = 0;
  let mut ix: u64 = asuint64(x);
  let iy: u64 = asuint64(y);
  let mut topx: u32 = top12(x);
  let topy: u32 = top12(y);
  if topx.wrapping_sub(0x001) >= 0x7ff - 0x001 || (topy & 0x7ff).wrapping_sub(0x3be) >= 0x43e - 0x3be {
    /* Note: if |y| > 1075 * ln2 * 2^53 ~= 0x1.749p62 then pow(x,y) = inf/0
       and if |y| < 2^-54 / 1075 ~= 0x1.e7b6p-65 then pow(x,y) = +-1.  */
    /* Special cases: (x < 0x1p-126 or inf or nan) or
       (|y| < 0x1p-65 or |y| >= 0x1p63 or nan).  */
    if zeroinfnan(iy) {
      if iy.wrapping_mul(2) == 0 {
        return if issignaling(x) { x + y } else { 1.0 };
      }
      if ix == asuint64(1.0) {
        return if issignaling(y) { x + y } else { 1.0 };
      }
      if ix.wrapping_mul(2) > 2u64.wrapping_mul(asuint64(f64::INFINITY))
        || iy.wrapping_mul(2) > 2u64.wrapping_mul(asuint64(f64::INFINITY))
      {
        return x + y;
      }
      if ix.wrapping_mul(2) == 2u64.wrapping_mul(asuint64(1.0)) {
        return 1.0;
      }
      if (ix.wrapping_mul(2) < 2u64.wrapping_mul(asuint64(1.0))) == ((iy >> 63) == 0) {
        return 0.0; /* |x|<1 && y==inf or |x|>1 && y==-inf.  */
      }
      return y * y;
    }
    if zeroinfnan(ix) {
      let mut x2: f64 = x * x;
      if ix >> 63 != 0 && checkint(iy) == 1 {
        x2 = -x2;
        sign_bias = 1;
      }
      if ix.wrapping_mul(2) == 0 && iy >> 63 != 0 {
        return math_divzero(sign_bias);
      }
      return if iy >> 63 != 0 { 1.0 / x2 } else { x2 };
    }
    /* Here x and y are non-zero finite.  */
    if ix >> 63 != 0 {
      /* Finite x < 0.  */
      let yint: i32 = checkint(iy);
      if yint == 0 {
        return math_invalid(x);
      }
      if yint == 1 {
        sign_bias = SIGN_BIAS;
      }
      ix &= 0x7fffffffffffffff;
      topx &= 0x7ff;
    }
    if (topy & 0x7ff).wrapping_sub(0x3be) >= 0x43e - 0x3be {
      /* Note: sign_bias == 0 here because y is not odd.  */
      if ix == asuint64(1.0) {
        return 1.0;
      }
      if (topy & 0x7ff) < 0x3be {
        /* |y| < 2^-65, x^y ~= 1 + y*log(x).  */
        return if ix > asuint64(1.0) { 1.0 + y } else { 1.0 - y };
      }
      return if (ix > asuint64(1.0)) == (topy < 0x800) { math_oflow(0) } else { math_uflow(0) };
    }
    if topx == 0 {
      /* Normalize subnormal x so exponent becomes negative.  */
      ix = asuint64(x * f64::from_bits(0x4330000000000000)); // 0x1p52
      ix &= 0x7fffffffffffffff;
      ix = ix.wrapping_sub(52u64 << 52);
    }
  }

  let mut lo: f64 = 0.0;
  let hi: f64 = pow_log_inline(ix, &mut lo);
  // ehi = y * hi; elo = y * lo + __builtin_fma (y, hi, -ehi);  (y * lo contracted)
  let ehi: f64 = y * hi;
  let elo: f64 = y.mul_add(lo, y.mul_add(hi, -ehi));
  pow_exp_inline(ehi, elo, sign_bias)
}

