/// Top 16 bits of a double.
#[inline(always)]
fn top16(x: f64) -> u32 {
  (asuint64(x) >> 48) as u32
}

const LOG_OFF: u64 = 0x3fe6000000000000;

/// C `log(double)` (glibc 2.44 `__log_fma`). Use instead of `f64::ln`.
pub fn ln(x: f64) -> f64 {
  let mut ix: u64 = asuint64(x);
  let top: u32 = top16(x);

  const LO: u64 = 0x3fee000000000000; // asuint64 (1.0 - 0x1p-4)
  const HI: u64 = 0x3ff1090000000000; // asuint64 (1.0 + 0x1.09p-4)
  if ix.wrapping_sub(LO) < HI - LO {
    /* Handle close to 1.0 inputs separately.  */
    /* Fix sign of zero with downward rounding when x==1.  */
    if ix == asuint64(1.0) {
      return 0.0;
    }
    let r: f64 = x - 1.0;
    let r2: f64 = r * r;
    let r3: f64 = r * r2;
    let b = |i: usize| c(LOG_POLY1[i]);
    // y = r3 * (B[1] + r * B[2] + r2 * B[3]
    //           + r3 * (B[4] + r * B[5] + r2 * B[6]
    //                   + r3 * (B[7] + r * B[8] + r2 * B[9] + r3 * B[10])));
    let p0: f64 = b(3).mul_add(r2, b(2).mul_add(r, b(1)));
    let p1: f64 = b(6).mul_add(r2, b(5).mul_add(r, b(4)));
    let p2: f64 = b(10).mul_add(r3, b(9).mul_add(r2, b(8).mul_add(r, b(7))));
    let poly: f64 = p2.mul_add(r3, p1).mul_add(r3, p0);
    /* Worst-case error is around 0.507 ULP.  */
    // w = r * 0x1p27; double rhi = r + w - w;
    let w0: f64 = r.mul_add(134217728.0, r);
    let rhi: f64 = (-r).mul_add(134217728.0, w0);
    let rlo: f64 = r - rhi;
    // w = rhi * rhi * B[0]; /* B[0] == -0.5.  */ hi = r + w; lo = r - hi + w;
    let rhi2: f64 = rhi * rhi;
    let hi: f64 = rhi2.mul_add(b(0), r);
    let mut lo: f64 = rhi2.mul_add(b(0), r - hi);
    // lo += B[0] * rlo * (rhi + r);
    lo = (b(0) * rlo).mul_add(r + rhi, lo);
    // y += lo; (contracted with y = r3 * (...))
    let mut y: f64 = poly.mul_add(r3, lo);
    y += hi;
    return y;
  }
  if top.wrapping_sub(0x0010) >= 0x7ff0 - 0x0010 {
    /* x < 0x1p-1022 or inf or nan.  */
    if ix.wrapping_mul(2) == 0 {
      return math_divzero(1);
    }
    if ix == asuint64(f64::INFINITY) {
      /* log(inf) == inf.  */
      return x;
    }
    if (top & 0x8000) != 0 || (top & 0x7ff0) == 0x7ff0 {
      return math_invalid(x);
    }
    /* x is subnormal, normalize it.  */
    ix = asuint64(x * f64::from_bits(0x4330000000000000)); // 0x1p52
    ix = ix.wrapping_sub(52u64 << 52);
  }

  /* x = 2^k z; where z is in range [OFF,2*OFF) and exact.
     The range is split into N subintervals.
     The ith subinterval contains z and c is near its center.  */
  let tmp: u64 = ix.wrapping_sub(LOG_OFF);
  let i: usize = ((tmp >> (52 - LOG_TABLE_BITS)) % N_LOG) as usize;
  let k: i32 = ((tmp as i64) >> 52) as i32; /* arithmetic shift */
  let iz: u64 = ix.wrapping_sub(tmp & (0xfffu64 << 52));
  let invc: f64 = c(LOG_TAB[2 * i]);
  let logc: f64 = c(LOG_TAB[2 * i + 1]);
  let z: f64 = asdouble(iz);

  /* log(x) = log1p(z/c-1) + log(c) + k*Ln2.  */
  /* r ~= z/c - 1, |r| < 1/(2*N).  */
  /* rounding error: 0x1p-55/N.  */
  let r: f64 = z.mul_add(invc, -1.0);
  let kd: f64 = k as f64;

  /* hi + lo = r + log(c) + k*Ln2.  */
  // w = kd * Ln2hi + logc;
  let w: f64 = c(LOG_LN2HI).mul_add(kd, logc);
  let hi: f64 = r + w;
  // lo = w - hi + r + kd * Ln2lo;
  let lo: f64 = c(LOG_LN2LO).mul_add(kd, (w - hi) + r);

  /* log(x) = lo + (log1p(r) - r) + hi.  */
  let r2: f64 = r * r; /* rounding error: 0x1p-54/N^2.  */
  /* Worst case error if |y| > 0x1p-5:
     0.5 + 4.13/N + abs-poly-error*2^57 ULP (+ 0.002 ULP without fma)
     Worst case error if |y| > 0x1p-4:
     0.5 + 2.06/N + abs-poly-error*2^56 ULP (+ 0.001 ULP without fma).  */
  // y = lo + r2 * A[0] + r * r2 * (A[1] + r * A[2] + r2 * (A[3] + r * A[4])) + hi;
  let a = |i: usize| c(LOG_POLY[i]);
  let s0: f64 = a(0).mul_add(r2, lo);
  let q: f64 = a(4).mul_add(r, a(3)).mul_add(r2, a(2).mul_add(r, a(1)));
  (r * r2).mul_add(q, s0) + hi
}

