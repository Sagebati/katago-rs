//! Transcendental functions bit-identical to the glibc that produced the fixtures
//! (docs/PORTING.md §6 item 3). Not a port of any upstream KataGo file.
//!
//! Ported from ARM optimized-routines (https://github.com/ARM-software/optimized-routines)
//! @ f67e7daa5457646fad9f75580263dba654c988aa: math/exp.c, math/exp_data.c, math/log.c,
//! math/log_data.c, math/pow.c, math/pow_log_data.c, math/expf.c, math/exp2f_data.c.
//! Copyright (c) 2017-2026, Arm Limited. SPDX-License-Identifier: MIT OR Apache-2.0 WITH
//! LLVM-exception (we use it under MIT, the crate's license).
//!
//! Why: on wasm32-unknown-unknown, Rust's `f64::exp/ln/powf` and `f32::exp` come from
//! compiler-builtins' libm (fdlibm/musl-derived), which differs from glibc in the last ulp for
//! ~3-10% of inputs. That desyncs `Rand::next_gamma`/`next_gaussian_truncated`'s accept/reject
//! loops and every later draw. katago-core therefore never calls the std methods
//! (clippy `disallowed_methods`, crates/katago-core/clippy.toml) and uses these on all targets.
//!
//! Which glibc build is reproduced: the fixtures come from glibc 2.44 on x86-64 with FMA, where
//! `exp`/`log`/`pow`/`expf` resolve (ifunc) to `__exp_fma`, `__log_fma`, `__pow_fma`,
//! `__expf_fma`: the same ARM sources compiled with `-mfma -mavx2` and GCC's default
//! `-ffp-contract=fast`, i.e. with `__FP_FAST_FMA` paths enabled **and** compiler-contracted
//! `a*b+c`. Each `mul_add` below is one `.FMA`/`.FMS`/`.FNMA` in GCC's GIMPLE for that build
//! (`gcc -O2 -mfma -mavx2 -frounding-math -fdump-tree-optimized` on glibc's
//! sysdeps/ieee754/{dbl-64,flt-32} copies of these files, whose results match the installed
//! libm on 2*10^7 inputs per function); plain `*`/`+` were not fused. Keep the operand order:
//! `a.mul_add(b, c)` = `.FMA (a, b, c)`. `mul_add` is a correctly rounded fma on every target
//! (hardware on x86-64 via libm `fma`, compiler-builtins' soft fma on wasm).
//! PORT NOTE: upstream run on an x86-64 CPU *without* FMA uses glibc's `__exp_sse2` etc. and
//! can differ in the last ulp; the fixtures (and this module) follow the FMA machine.
//!
//! Tables are the ARM data files' values as bit patterns, generated by a C program from
//! optimized-routines' data files and checked equal to glibc 2.44's copies.
//!
//! Scope: the transcendentals the in-scope upstream code calls through optimized-routines in
//! glibc. C `exp`→[`exp`], `log`→[`ln`], `pow`→[`powf`], `expf`→[`expf`]. `logf`/`powf` (float)
//! are not called by upstream code and not provided. Of the functions glibc implements
//! elsewhere, `tanhf` (CORE-MATH, correctly rounded) is [`tanhf`]: our own correctly rounded
//! double-double evaluation, not a port of glibc's code (see its section). `lgamma`/`lgamma_r`
//! (CORE-MATH, MIT, correctly rounded) are a port of glibc's copy in math/lgamma.rs. `expm1`
//! (fdlibm, `__expm1_fma`) is ported with glibc's FMA contractions like the ARM routines (see
//! its section). `atan`, `tan` (IBM Accurate Mathematical Library, LGPL) wrap the platform
//! libm (D13). `tanh`, `atanf` (CORE-MATH) and `log10` (fdlibm) are not here yet: see the
//! TODO(port) at the end of the file. `sqrt` is correctly rounded everywhere and stays
//! `f64::sqrt`.

