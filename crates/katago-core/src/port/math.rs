/// Handle cases that may overflow or underflow when computing the result that
/// is scale*(1+TMP) without intermediate rounding.  The bit representation of
/// scale is in SBITS, however it has a computed exponent that may have
/// overflown into the sign bit so that needs to be adjusted before using it as
/// a double.  (int32_t)KI is the k used in the argument reduction and exponent
/// adjustment of scale, positive k here means the result may overflow and
/// negative k means the result may underflow.
fn exp_specialcase(tmp: f64, mut sbits: u64, ki: u64) -> f64 {
  let scale: f64;
  let mut y: f64;

  if (ki & 0x80000000) == 0 {
    /* k > 0, the exponent of scale might have overflowed by <= 460.  */
    sbits = sbits.wrapping_sub(1009u64 << 52);
    scale = asdouble(sbits);
    // y = 0x1p1009 * (scale + scale * tmp);
    y = f64::from_bits(0x7f00000000000000) * tmp.mul_add(scale, scale);
    return y;
  }
  /* k < 0, need special care in the subnormal range.  */
  sbits = sbits.wrapping_add(1022u64 << 52);
  scale = asdouble(sbits);
  // y = scale + scale * tmp;  (not contracted: scale * tmp is reused below)
  let scale_tmp = tmp * scale;
  y = scale + scale_tmp;
  if y < 1.0 {
    /* Round y to the right precision before scaling it into the subnormal
       range to avoid double rounding that can cause 0.5+E/2 ulp error where
       E is the worst-case ulp error outside the subnormal range.  So this
       is only useful if the goal is better than 1 ulp worst-case error.  */
    let mut lo: f64 = scale_tmp + (scale - y);
    let hi: f64 = y + 1.0;
    lo += y + (1.0 - hi);
    y = (hi + lo) - 1.0;
    /* Avoid -0.0 with downward rounding.  */
    if y == 0.0 {
      y = 0.0;
    }
    /* The underflow exception needs to be signaled explicitly.  */
    // PORT NOTE: math_force_eval(0x1p-1022 * 0x1p-1022) only raises a flag; dropped.
  }
  y *= f64::from_bits(0x0010000000000000); // 0x1p-1022
  y
}

/// C `exp(double)` (glibc 2.44 `__exp_fma`). Use instead of `f64::exp`.
pub fn exp(x: f64) -> f64 {
  let mut abstop: u32;

  abstop = top12(x) & 0x7ff;
  if abstop.wrapping_sub(top12(f64::from_bits(0x3c90000000000000))) // 0x1p-54
    >= top12(512.0) - top12(f64::from_bits(0x3c90000000000000))
  {
    if abstop.wrapping_sub(top12(f64::from_bits(0x3c90000000000000))) >= 0x80000000 {
      /* Avoid spurious underflow for tiny x.  */
      /* Note: 0 is common input.  */
      return 1.0 + x;
    }
    if abstop >= top12(1024.0) {
      if asuint64(x) == asuint64(f64::NEG_INFINITY) {
        return 0.0;
      }
      if abstop >= top12(f64::INFINITY) {
        return 1.0 + x;
      }
      if asuint64(x) >> 63 != 0 {
        return math_uflow(0);
      } else {
        return math_oflow(0);
      }
    }
    /* Large x is special cased below.  */
    abstop = 0;
  }

  /* exp(x) = 2^(k/N) * exp(r), with exp(r) in [2^(-1/2N),2^(1/2N)].  */
  /* x = ln2/N*k + r, with int k and r in [-ln2/2N, ln2/2N].  */
  // z = InvLn2N * x; kd = z + Shift;  (contracted)
  let mut kd: f64 = c(EXP_INVLN2N).mul_add(x, c(EXP_SHIFT));
  let ki: u64 = asuint64(kd);
  kd -= c(EXP_SHIFT);
  // r = x + kd * NegLn2hiN + kd * NegLn2loN;
  let r: f64 = c(EXP_NEGLN2LON).mul_add(kd, c(EXP_NEGLN2HIN).mul_add(kd, x));
  /* 2^(k/N) ~= scale * (1 + tail).  */
  let idx: u64 = 2 * (ki % N_EXP);
  let top: u64 = ki << (52 - EXP_TABLE_BITS);
  let tail: f64 = asdouble(EXP_TAB[idx as usize]);
  /* This is only a valid scale when -1023*N < k < 1024*N.  */
  let sbits: u64 = EXP_TAB[idx as usize + 1].wrapping_add(top);
  /* exp(x) = 2^(k/N) * exp(r) ~= scale + scale * (tail + exp(r) - 1).  */
  /* Evaluation is optimized assuming superscalar pipelined execution.  */
  let r2: f64 = r * r;
  /* Without fma the worst case error is 0.25/N ulp larger.  */
  /* Worst case error is less than 0.5+1.11/N+(abs poly error * 2^53) ulp.  */
  // tmp = tail + r + r2 * (C2 + r * C3) + r2 * r2 * (C4 + r * C5);
  let t0: f64 = r + tail;
  let t1: f64 = c(EXP_POLY[1]).mul_add(r, c(EXP_POLY[0])).mul_add(r2, t0);
  let tmp: f64 = (r2 * r2).mul_add(c(EXP_POLY[3]).mul_add(r, c(EXP_POLY[2])), t1);
  if abstop == 0 {
    return exp_specialcase(tmp, sbits, ki);
  }
  let scale: f64 = asdouble(sbits);
  /* Note: tmp == 0 or |tmp| > 2^-200 and scale > 2^-739, so there
     is no spurious underflow here even without fma.  */
  // scale + scale * tmp
  tmp.mul_add(scale, scale)
}

