#[inline(always)]
fn top12f(x: f32) -> u32 {
  asuint(x) >> 20
}

/// C `expf(float)` (glibc 2.44 `__expf_fma`). Use instead of `f32::exp`.
pub fn expf(x: f32) -> f32 {
  let xd: f64 = x as f64;
  let abstop: u32 = top12f(x) & 0x7ff;
  if abstop >= top12f(88.0f32) {
    /* |x| >= 88 or x is nan.  */
    if asuint(x) == asuint(f32::NEG_INFINITY) {
      return 0.0f32;
    }
    if abstop >= top12f(f32::INFINITY) {
      return x + x;
    }
    if x > f32::from_bits(0x42b17217) {
      /* x > log(0x1p128) ~= 88.72 */
      return math_oflowf(0);
    }
    if x < f32::from_bits(0xc2cff1b4) {
      /* x < log(0x1p-150) ~= -103.97 */
      return math_uflowf(0);
    }
    if x < f32::from_bits(0xc2ce8ecf) {
      /* x < log(0x1p-149) ~= -103.28 */
      return math_may_uflowf(0);
    }
  }

  /* x*N/Ln2 = k + r with r in [-1/2, 1/2] and int k.  */
  // z = InvLn2N * xd; kd = (double) (z + SHIFT);  (contracted)
  let mut kd: f64 = c(EXP2F_INVLN2_SCALED).mul_add(xd, c(EXP2F_SHIFT));
  let ki: u64 = asuint64(kd);
  kd -= c(EXP2F_SHIFT);
  // r = z - kd;  (contracted with z = InvLn2N * xd)
  let r: f64 = c(EXP2F_INVLN2_SCALED).mul_add(xd, -kd);

  /* exp(x) = 2^(k/N) * 2^(r/N) ~= s * (C0*r^3 + C1*r^2 + C2*r + 1) */
  let mut t: u64 = EXP2F_TAB[(ki % N_EXP2F) as usize];
  t = t.wrapping_add(ki << (52 - EXP2F_TABLE_BITS));
  let s: f64 = asdouble(t);
  let z: f64 = c(EXP2F_POLY_SCALED[0]).mul_add(r, c(EXP2F_POLY_SCALED[1]));
  let r2: f64 = r * r;
  let mut y: f64 = c(EXP2F_POLY_SCALED[2]).mul_add(r, 1.0);
  y = z.mul_add(r2, y);
  y *= s;
  y as f32
}

