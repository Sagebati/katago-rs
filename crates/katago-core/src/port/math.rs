#[inline(always)]
fn asuint64(f: f64) -> u64 {
  f.to_bits()
}

#[inline(always)]
fn asdouble(i: u64) -> f64 {
  f64::from_bits(i)
}

#[inline(always)]
fn asuint(f: f32) -> u32 {
  f.to_bits()
}

/// `__math_xflow`: `y = (sign ? -y : y) * y`, which raises the exception and rounds.
#[inline(never)]
fn xflow(sign: u32, y: f64) -> f64 {
  let y2 = if sign != 0 { -y } else { y };
  y2 * y
}

/// `__math_uflow`
fn math_uflow(sign: u32) -> f64 {
  xflow(sign, f64::from_bits(0x1000000000000000)) // 0x1p-767
}

/// `__math_oflow`
fn math_oflow(sign: u32) -> f64 {
  xflow(sign, f64::from_bits(0x7000000000000000)) // 0x1p769
}

/// `__math_divzero`
fn math_divzero(sign: u32) -> f64 {
  (if sign != 0 { -1.0 } else { 1.0 }) / 0.0
}

/// `__math_invalid`
#[allow(clippy::eq_op)] // (x - x) / (x - x) is how C produces the NaN and raises FE_INVALID
fn math_invalid(x: f64) -> f64 {
  (x - x) / (x - x)
}

#[inline(never)]
fn xflowf(sign: u32, y: f32) -> f32 {
  let y2 = if sign != 0 { -y } else { y };
  y2 * y
}

/// `__math_uflowf`
fn math_uflowf(sign: u32) -> f32 {
  xflowf(sign, f32::from_bits(0x10000000)) // 0x1p-95f
}

/// `__math_may_uflowf`
fn math_may_uflowf(sign: u32) -> f32 {
  xflowf(sign, f32::from_bits(0x1a200000)) // 0x1.4p-75f
}

/// `__math_oflowf`
fn math_oflowf(sign: u32) -> f32 {
  xflowf(sign, f32::from_bits(0x70000000)) // 0x1p97f
}

/// `issignaling` (glibc): NaN with the quiet bit clear.
fn issignaling(x: f64) -> bool {
  let ix = asuint64(x);
  (ix ^ 0x0008000000000000) & 0x7fffffffffffffff > 0x7ff8000000000000
}

/// Top 12 bits of a double (sign and exponent bits).
#[inline(always)]
fn top12(x: f64) -> u32 {
  (asuint64(x) >> 52) as u32
}

const EXP_TABLE_BITS: u32 = 7;
const N_EXP: u64 = 1 << EXP_TABLE_BITS;
const LOG_TABLE_BITS: u32 = 7;
const N_LOG: u64 = 1 << LOG_TABLE_BITS;
const POW_LOG_TABLE_BITS: u32 = 7;
const N_POW_LOG: u64 = 1 << POW_LOG_TABLE_BITS;
const EXP2F_TABLE_BITS: u32 = 5;
const N_EXP2F: u64 = 1 << EXP2F_TABLE_BITS;

#[inline(always)]
fn c(bits: u64) -> f64 {
  f64::from_bits(bits)
}

